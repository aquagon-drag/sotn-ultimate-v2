# SEL's text pack reader (mods/sotn-ultimate/src/menu/sel_text_cd.c,
# ModTextReady) -> src/st/sel/mod_text_cd.inc: its cc1 output (SEL's cc1
# and flags, as tools/builds/gen.py compiles 2C048.c, without the debug
# info), as C string lines for config_us.c's __asm__, which puts it in SEL's
# dead config copy after the PSP staff roll (this cc1 ignores section
# attributes). Its labels get a prefix, .text goes (the copy is .data), and
# its state words follow the code.
#   gen_sel_text_cd.sh           write src/st/sel/mod_text_cd.inc
#   gen_sel_text_cd.sh --check   fail if it is not this file's output
set -euo pipefail
cd "$(dirname "$0")/../../.."
SRC=mods/sotn-ultimate/src/menu/sel_text_cd.c
DST=src/st/sel/mod_text_cd.inc
# the main SDK's CD functions: SEL's link has no symbol for them (its other
# code does not call them) and gas cannot jal an absolute address from
# .data, so the C calls them through their config/symbols.us.txt addresses
sym() { grep -oE "^$1 = 0x[0-9A-Fa-f]+;" config/symbols.us.txt | grep -oE "0x[0-9A-Fa-f]+"; }
CDDEFS="-DSEL_CD_INIT=$(sym CdInit) -DSEL_CD_READY_CB=$(sym CdReadyCallback) -DSEL_CD_DATA_CB=$(sym CdDataCallback)"
tmp=$(mktemp)
trap 'rm -f "$tmp" "$tmp.s"' EXIT
VERSION=us mipsel-linux-gnu-cpp -Isrc/st/sel -lang-c -Iinclude -Iinclude/psxsdk \
    -undef -Wall -fno-builtin -Dmips -D__GNUC__=2 -D__OPTIMIZE__ -D__mips__ \
    -D__mips -Dpsx -D__psx__ -D__psx -D_PSYQ -D__EXTENSIONS__ -D_MIPSEL \
    -D_LANGUAGE_C -DLANGUAGE_C -DNO_LOGS -DHACKS -DUSE_INCLUDE_ASM \
    -D_internal_version_us -DSOTN_STR $CDDEFS "$SRC" |
    tools/sotn_str/target/release/sotn_str process |
    iconv --from-code=UTF-8 --to-code=Shift-JIS |
    bin/cc1-psx-26 -G0 -w -funsigned-char -fpeephole -ffunction-cse \
        -fpcc-struct-return -fcommon -msoft-float -quiet -mcpu=3000 \
        -fgnu-linker -mgas -O2 > "$tmp.s"
python3 - "$tmp.s" "$tmp" <<'PYEOF'
import re, sys
src, out = sys.argv[1], sys.argv[2]
lines = []
for l in open(src):
    l = l.rstrip("\n")
    s = l.strip()
    # the file's header, its comments and the .include cc1 copies from
    # the headers (config_us.c's own output has it), .text (the copy is .data).
    # .ent / .end stay (gas warns they are not in .text): maspsx sets
    # noreorder from a function's .ent, which its delay slots need
    if (not s or s.startswith(".file") or s in ("gcc2_compiled.:", "__gnu_compiled_c:")
            or s.startswith(".include") or s == ".text" or s in ("#APP", "#NO_APP")
            or (s.startswith("#") and not s.startswith("#nop") and not s.startswith("#.set"))):
        continue
    if re.match(r"\s*\.(data|rdata|bss|sdata|section)\b", l):
        sys.exit("gen_sel_text_cd: %s has data of its own: %s" % (src, s))
    l = re.sub(r"\$L(\d+)", r"$LTXC\1", l)
    l = re.sub(r"\s+# [-0-9a-fx]+$", "", l)  # value comments
    lines.append(l)
for v in ("g_ModTextCd", "g_ModTextCdOvl", "g_ModTextCdT0", "g_ModTextCdTry",
          "g_ModTextCdNext", "g_ModTextCdGate", "g_ModTextCdFail"):
    lines += ["\t.globl\t%s" % v, "%s:" % v, "\t.word\t0"]
with open(out, "w") as f:
    f.write("// SPDX-License-Identifier: AGPL-3.0-or-later\n"
            "// Generated by mods/sotn-ultimate/tools/gen_sel_text_cd.sh from\n"
            "// mods/sotn-ultimate/src/menu/sel_text_cd.c: do not edit\n")
    for l in lines:
        f.write('"%s\\n"\n' % l.replace("\\", "\\\\").replace('"', '\\"'))
PYEOF
if [ "${1:-}" = --check ]; then
    if ! cmp -s "$tmp" "$DST"; then
        echo "FAIL $DST is not $SRC's output (run mods/sotn-ultimate/tools/gen_sel_text_cd.sh)"
        exit 1
    fi
    echo "OK   $DST is $SRC's cc1 output"
else
    cp "$tmp" "$DST"
fi
