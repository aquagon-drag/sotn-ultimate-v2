#if defined(MOD_SATURN) && defined(MOD_DRA_CONFIG)
// Saturn port: the System screen's "Ultimate settings" row and popup
// (mods/sotn-ultimate/src/menu/sysopt.c, in BIN/ARC_F2.BIN, loaded only
// in Alucard games): the three stubs menu.c calls instead of func_800F5E68 /
// MenuHandleCursorInput / MenuSoundConfigDraw, code in DRA's data, whose
// pad had room (its code has none). Each jumps to that code's entry (its
// header: MOD_SYSOPT_MAGIC, then the three entries) when the magic is
// there, else to the retail function, with the caller's arguments
// untouched (registers and stack; only $8-$13 are used)
#define MOD_SYSOPT_S(x) #x
#define MOD_SYSOPT_XS(x) MOD_SYSOPT_S(x)
#define MOD_SYSOPT_A MOD_SYSOPT_XS(MOD_SYSOPT_ADDR)
// maspsx adds nops around branches and loads (it ignores .set noreorder),
// so all but the relocated lui / addiu are raw words (19 words in all;
// mods/sotn-ultimate/tools/build_sysopt.sh checks them in the built DRA):
//   ModSysOptSound: lui/addiu $13 = MenuSoundConfigDraw; b ModSysOptGo;
//                   li $11, 12
//   ModSysOptBox:   lui/addiu $13 = func_800F5E68; b ModSysOptGo; li $11, 4
//   ModSysOptInput: lui/addiu $13 = MenuHandleCursorInput; li $11, 8
//   ModSysOptGo:    $8 = %hi(ADDR) (= the magic; %lo(ADDR) = 0xDBF0 in
//                   the raw lw words); $9 = magic word;
//                   $12 = entry word ($8 + $11 + %lo(ADDR));
//                   if ($9 == $8) $13 = $12; jr $13
__asm__(
    ".data\n" // (gcc is in .data here: it ends there too)
    ".align 2\n"
    // the pause menu's Bestiary row (step 7, bestiary_menu.h): entries 16,
    // 20 and 24 of the header, for func_800F8754 (the main box's rows),
    // MENU_STEP_OPENED's MenuHandleCursorInput and MenuFamiliarsDraw
    ".globl ModBestMain\n"
    "ModBestMain:\n"
    "lui $13, %hi(func_800F8754)\n"
    "addiu $13, $13, %lo(func_800F8754)\n"
    ".word 0x10000014\n" // b ModSysOptGo
    ".word 0x340B0010\n" // li $11, 16 (delay slot)
    ".globl ModBestInput\n"
    "ModBestInput:\n"
    "lui $13, %hi(MenuHandleCursorInput)\n"
    "addiu $13, $13, %lo(MenuHandleCursorInput)\n"
    ".word 0x10000010\n" // b ModSysOptGo
    ".word 0x340B0014\n" // li $11, 20 (delay slot)
    ".globl ModBestDraw\n"
    "ModBestDraw:\n"
    "lui $13, %hi(MenuFamiliarsDraw)\n"
    "addiu $13, $13, %lo(MenuFamiliarsDraw)\n"
    ".word 0x1000000C\n" // b ModSysOptGo
    ".word 0x340B0018\n" // li $11, 24 (delay slot)
    ".globl ModSysOptSound\n"
    "ModSysOptSound:\n"
    "lui $13, %hi(MenuSoundConfigDraw)\n"
    "addiu $13, $13, %lo(MenuSoundConfigDraw)\n"
    ".word 0x10000008\n" // b ModSysOptGo
    ".word 0x340B000C\n" // li $11, 12 (delay slot)
    ".globl ModSysOptBox\n"
    "ModSysOptBox:\n"
    "lui $13, %hi(func_800F5E68)\n"
    "addiu $13, $13, %lo(func_800F5E68)\n"
    ".word 0x10000004\n" // b ModSysOptGo
    ".word 0x340B0004\n" // li $11, 4 (delay slot)
    ".globl ModSysOptInput\n"
    "ModSysOptInput:\n"
    "lui $13, %hi(MenuHandleCursorInput)\n"
    "addiu $13, $13, %lo(MenuHandleCursorInput)\n"
    ".word 0x340B0008\n" // li $11, 8
    "ModSysOptGo:\n"
    "lui $8, %hi(" MOD_SYSOPT_A ")\n" // = MOD_SYSOPT_MAGIC
    ".word 0x8D09DBF0\n"              // lw $9, %lo(ADDR)($8): the magic?
    ".word 0x010B5021\n"              // addu $10, $8, $11
    ".word 0x8D4CDBF0\n"              // lw $12, %lo(ADDR)($10): its entry
    ".word 0x15280002\n"              // bne $9, $8, 1f
    ".word 0\n"
    ".word 0x01806821\n" // move $13, $12
    ".word 0x01A00008\n" // 1: jr $13
    ".word 0\n");
#endif

