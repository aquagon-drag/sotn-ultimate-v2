"""The retranslation pack's fit and mapping report (text_rt.py --report F).

It quotes the retranslation's text, so it is written OUTSIDE the
repository (a path the caller gives); nothing here is committed output.
Lists: every string that does not fit where the US code draws it (context,
limit, the retranslated text, by how much, what the build shows for now);
the characters the US fonts lack and what they became; the entries where
the patch and the US tables disagree on having text; the Saturn-only
entries; the save messages; the menu words left to decide."""
import collections

import text_rt as rt

TABLE_NAME = {"equip": "Equipment", "acc": "Accessory", "relic": "Relic", "spell": "Spell",
              "enemy": "Enemy", "menu": "g_MenuStr", "help": "Help line"}


def us_text(e):
    return rt.from_s(e.us) if e.kind == "s" else rt.from_bios(e.us)


def new_text(e):
    return rt.from_s(e.new) if e.kind == "s" else rt.from_bios(e.new)


def unit(e):
    if e.context == "menu" or rt.LIMITS[e.context][0] == "chars":
        return "ch"
    return "px"


def md(s):
    return (s or "").replace("|", "\\|").replace("\n", " / ")


def write(path, res):
    ents, saves, notes = res
    out = []
    w = out.append
    w("# Step 6a fit report: retranslation strings vs the US drawing code\n")
    w("Generated by `mods/sotn-ultimate/tools/text_rt.py --report` from the builder's "
      "`disks/jpre/DRA.BIN`. It quotes the retranslation (romhacking.net #1427), so it lives "
      "outside the repository.\n")
    w("## How to read it\n")
    w("* **8x8 contexts** (item, enemy and menu names) count characters: the US font is 8 px "
      "wide, every character.")
    w("* **BIOS-font contexts** (relic and spell names, descriptions, help lines, save "
      "messages) count pixels. The US code draws them with the console BIOS's Shift-JIS font, "
      "proportionally (menu.c func_800F99B8). The widths here are an **estimate**: the same "
      "algorithm run on the public-domain Shinonome 14-dot font of PCSX-Redux's OpenBIOS, not "
      "on Sony's BIOS font. Calibration: the widest US help line measures exactly 288 px and "
      "the widest US relic name exactly 120 px, the renderer's two limits. Treat entries "
      "within about 10 px of a limit as \"check in the emulator\".")
    w("* **Build now** is the provisional choice: `us` = the US text is shown for that entry "
      "(the retranslation does not fit and would be cut or overlap); `rt` = the retranslation "
      "as is. Change any entry with `disks/jpre/rt_overrides.tsv` (format: "
      "`mods/sotn-ultimate/tools/text_rt_overrides.template.tsv`): `rt` (keep the "
      "retranslation, overflowing), `us`, or `text` with your own wording.\n")
    w("## Limits (from the US code)\n")
    w("| Context | Unit | Limit | Where |")
    w("|---|---|---|---|")
    for k, (u, lim, where) in rt.LIMITS.items():
        w("| %s | %s | %s | %s |" % (k, u, lim if lim is not None else "per string", md(where)))
    w("")
    w("g_MenuStr limits (characters): " + ", ".join(
        "%d: %d" % (i, n) for i, n in sorted(rt.MENU_LIMIT.items())) + "\n")

    over = [e for e in ents if e.source in ("rt", "saturn") and e.limit is not None and
            (e.measure is None or e.measure > e.limit)]
    near = [e for e in ents if e.source == "rt" and e.limit is not None and unit(e) == "px" and
            e.measure is not None and e.limit - 10 < e.measure <= e.limit]
    by = collections.defaultdict(list)
    for e in over:
        by[(e.table, e.field)].append(e)
    w("## Strings that do not fit (%d)\n" % len(over))
    for (t, f), L in sorted(by.items()):
        w("### %s %s (%d)\n" % (TABLE_NAME[t], f, len(L)))
        w("| Index | Context | Limit | Retranslation | Measure | Over by | US text | Build now |")
        w("|---|---|---|---|---|---|---|---|")
        for e in sorted(L, key=lambda e: e.idx):
            w("| %d (0x%X) | %s%s | %s %s | %s | %s | %s | %s | %s |" % (
                e.idx, e.idx, e.context, " (consumable)" if e.consumable else "", e.limit, unit(e),
                md(e.rt), e.measure, (e.measure - e.limit) if e.measure is not None else "?",
                md(us_text(e)), "us" if e.new == e.us else "rt"))
        w("")
    w("## Within 10 px of a limit (BIOS-font estimate; check in the emulator) (%d)\n" % len(near))
    w("| Table | Index | Field | Retranslation | Estimate | Limit |")
    w("|---|---|---|---|---|---|")
    for e in sorted(near, key=lambda e: (e.table, e.idx)):
        w("| %s | %d | %s | %s | %d | %d |" % (e.table, e.idx, e.field, md(e.rt), e.measure, e.limit))
    w("")
    # characters
    subs = collections.Counter()
    where = collections.defaultdict(set)
    for e in ents:
        if e.source != "rt" or not e.rt:
            continue
        for c in e.rt:
            if c in rt.PLAIN or c in "↘":
                subs[(c, e.kind)] += 1
                where[(c, e.kind)].add("%s %d" % (e.table, e.idx))
    w("## Characters the US fonts lack\n")
    w("| Character | Font | Becomes | Uses | Where |")
    w("|---|---|---|---|---|")
    for (c, k), n in sorted(subs.items()):
        to = rt.PLAIN.get(c) or ("＼ (full-width reverse solidus, 0x815F)" if c == "↘" else "?")
        w("| %s | %s | %s | %d | %s |" % (c, "8x8" if k == "s" else "BIOS", to, n,
                                          ", ".join(sorted(where[(c, k)])[:8])))
    w("\nThe patch's two-letter tiles (ENC8 0x60-0x6F) and DTE pairs (ENC12 0x80-0xFF) are "
      "expanded to plain letters. Spell combos keep the US glyphs (the same inputs; the patch "
      "draws its charge mark as an icon).\n")
    # mismatches
    w("## Where the patch and the US tables disagree on having text\n")
    w("| Table | Index | Field | Retranslation | US | Build |")
    w("|---|---|---|---|---|---|")
    n = 0
    for e in ents:
        if e.source == "saturn":
            continue
        a, b = (e.rt or "").strip(), us_text(e).strip()
        if e.source == "keep" and e.table not in ("menu",) and e.field != "combo":
            continue
        if bool(a) != bool(b) and e.field != "combo":
            n += 1
            w("| %s | %d | %s | %s | %s | %s |" % (e.table, e.idx, e.field, md(a) or "(empty)",
                                                  md(b) or "(empty)", e.action))
    if not n:
        w("| | | | none | | |")
    w("")
    w("## Saturn-only entries (the mod's names in Title Case; descriptions stay the mod's)\n")
    w("| Table | Index | Mod name | This pack |")
    w("|---|---|---|---|")
    for e in ents:
        if e.source == "saturn":
            w("| %s | %d | %s | %s |" % (e.table, e.idx, md(us_text(e)), md(new_text(e))))
    w("")
    w("## g_MenuStr words without a proven source\n")
    for e in ents:
        if e.table == "menu" and e.note:
            w("* %d (US %r): %s. Kept the US word." % (e.idx, us_text(e), e.note))
    for i, why in sorted(rt.MENU_KEEP.items()):
        w("* %d: kept (%s)." % (i, why))
    w("")
    w("## Save point messages (code literals: rewritten in place only)\n")
    w("| US literal | Retranslation | Estimate | Box | Build |")
    w("|---|---|---|---|---|")
    for addr, room, us, new, text, wd, box, why, grp in saves:
        w("| %s | %s | %s | %s | %s |" % (md(rt.from_bios(us.rstrip(b"\0"))), md(text), wd, box or "slot box",
                                         "rt" if new else "us: " + why))
    w("")
    w("## Counts\n")
    c = collections.Counter((e.table, e.field, e.action) for e in ents)
    w("| Table | Field | Action | Entries |")
    w("|---|---|---|---|")
    for k in sorted(c):
        w("| %s | %s | %s | %d |" % (k + (c[k],)))
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("text_rt: report written to %s" % path)
